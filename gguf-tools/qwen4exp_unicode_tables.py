#!/usr/bin/env python3
"""Codepoint classes of the qwen35 pre-tokenizer regex, as C range tables.

Qwen3.8-Flash-Next's tokenizer splits text with a `regex`-module pattern over
\\p{L}, \\p{M}, \\p{N} and \\s.  ds4 approximated those classes from short
hand-written lists, which drifts from the reference on combining marks,
non-decimal numbers (superscripts, fractions, roman numerals), symbols and
the less common spaces.  This writes the exact classes -- as the `regex`
release it runs under defines them -- so the C splitter can match the
checkpoint's tokenizer.json byte for byte.

  python3 gguf-tools/qwen4exp_unicode_tables.py > ds4_qwen4exp_unicode.inc
"""
import sys

import regex

CLASSES = (("letter", r"\p{L}"), ("mark", r"\p{M}"), ("number", r"\p{N}"), ("space", r"\s"))


def ranges_of(pattern: str):
    pat = regex.compile(pattern, regex.V1)
    out, lo, prev = [], None, None
    for cp in range(0x110000):
        hit = not (0xD800 <= cp <= 0xDFFF) and pat.match(chr(cp)) is not None
        if hit:
            if lo is None:
                lo = cp
            prev = cp
        elif lo is not None:
            out.append((lo, prev))
            lo = None
    if lo is not None:
        out.append((lo, prev))
    return out


def main() -> None:
    w = sys.stdout.write
    w("/* Generated by gguf-tools/qwen4exp_unicode_tables.py (regex %s): the\n" % regex.__version__)
    w(" * codepoint classes of the qwen35 pre-tokenizer.  Do not edit; regenerate. */\n\n")
    w("typedef struct { uint32_t lo, hi; } q4e_urange;\n\n")
    for name, pattern in CLASSES:
        rs = ranges_of(pattern)
        w("static const q4e_urange q4e_%s_ranges[%d] = {\n" % (name, len(rs)))
        for i in range(0, len(rs), 4):
            w("    " + " ".join("{0x%05x, 0x%05x}," % r for r in rs[i:i + 4]) + "\n")
        w("};\n\n")


if __name__ == "__main__":
    main()
